"""Toolchain identity: everything outside the project root that affects a phase
(docs/format.md).

* ``python``: interpreter version.
* ``platform``: OS, CPU architecture and C library. A cached ``build_dir``
  contains native executables (Verilator, GHDL/LLVM), which only run where
  they were built for.
* ``cocotb``: version and a hash of the *content* of the installed
  distribution, so a locally modified install is not mistaken for the release.
* ``simulator``: the version text of every tool the runner invokes, including
  the C/C++ compiler for runners that compile native code.
* ``shim``: ``cocotb_cache.__version__``.
* ``image``: ``COCOTB_CACHE_IMAGE`` if set (the project's container sets it
  from a content hash of the image); absent otherwise.

Everything is computed once per process. If a tool cannot be identified the
caller must skip the cache (:class:`IdentityError`).
"""

from __future__ import annotations

import functools
import os
import platform as _platform
import subprocess
import sys
from importlib import metadata
from pathlib import Path

from . import __version__
from .hashing import canonical_hash, sha256_file
from .manifest import Toolchain

# Version commands per runner class. The first paragraph of each output (up to
# the first blank line) is the identity; license boilerplate follows it.
SIMULATOR_COMMANDS: dict[str, tuple[tuple[str, ...], ...]] = {
    "Icarus": (("iverilog", "-V"), ("vvp", "-V")),
    "Verilator": (("verilator", "--version"), ("g++", "--version"), ("make", "--version")),
    "Ghdl": (("ghdl", "--version"), ("gcc", "--version")),
    "Nvc": (("nvc", "--version"),),
}
COMMAND_TIMEOUT_S = 30

# Files of an installed distribution that differ between otherwise identical
# installs (written by the installer, or generated bytecode).
_INSTALLER_FILES = frozenset({"RECORD", "INSTALLER", "REQUESTED", "direct_url.json"})


class IdentityError(RuntimeError):
    """The toolchain could not be identified; the cache must be skipped."""


def first_paragraph(text: str) -> str:
    """Lines up to the first blank line, stripped (the version part of --version)."""
    lines = []
    for line in text.splitlines():
        if not line.strip():
            if lines:
                break
            continue
        lines.append(line.rstrip())
    return "\n".join(lines)


@functools.lru_cache(maxsize=None)
def _tool_version(cmd: tuple[str, ...]) -> str:
    try:
        res = subprocess.run(
            list(cmd), capture_output=True, text=True, timeout=COMMAND_TIMEOUT_S, stdin=subprocess.DEVNULL
        )
    except (OSError, subprocess.TimeoutExpired) as e:
        raise IdentityError(f"cannot run {' '.join(cmd)!r}: {e}") from e
    text = first_paragraph(res.stdout) or first_paragraph(res.stderr)
    if res.returncode != 0 or not text:
        raise IdentityError(f"{' '.join(cmd)!r} gave no version (exit {res.returncode})")
    return text


def simulator_identity(runner_name: str) -> str:
    """Version text of every tool the runner uses, one paragraph per tool."""
    try:
        commands = SIMULATOR_COMMANDS[runner_name]
    except KeyError:
        raise IdentityError(f"no identity commands for runner {runner_name!r}") from None
    return "\n---\n".join(_tool_version(cmd) for cmd in commands)


def platform_identity() -> str:
    """OS, architecture and C library, e.g. ``linux-x86_64-glibc2.39``."""
    libc, libc_version = _platform.libc_ver()
    return f"{sys.platform}-{_platform.machine()}-{libc or 'libc'}{libc_version}"


def python_identity() -> str:
    return f"{sys.implementation.name}-{_platform.python_version()}"


def dist_content_hash(dist: metadata.Distribution) -> str:
    """Hash of the content of an installed distribution.

    Every file listed in its RECORD (inside site-packages; scripts outside it
    embed the venv path and are skipped) is hashed by its actual content, not
    by the hash RECORD claims, so a modified install is detected. Bytecode
    and installer-specific files are excluded so that two installs of the same
    wheel give the same hash on any machine.

    An editable install has no package files in its RECORD; its packages are
    hashed from the source tree instead.
    """
    entries: list[list[str]] = []
    for f in dist.files or ():
        parts = f.parts
        if not parts or parts[0] == ".." or "__pycache__" in parts or f.suffix == ".pyc":
            continue
        if parts[0].endswith(".dist-info") and parts[-1] in _INSTALLER_FILES:
            continue
        if parts[0].startswith("__editable__"):
            continue
        path = Path(f.locate())
        if path.is_file():
            entries.append([f.as_posix(), sha256_file(path)[0]])
    if _is_editable(dist):
        entries.extend(_editable_entries(dist))
    if not entries:
        raise IdentityError(f"no files found for distribution {dist.metadata['Name']!r}")
    return canonical_hash(sorted(entries))


def _is_editable(dist: metadata.Distribution) -> bool:
    import json

    text = dist.read_text("direct_url.json")
    if not text:
        return False
    try:
        return bool(json.loads(text).get("dir_info", {}).get("editable"))
    except (ValueError, AttributeError):
        return False


def _editable_entries(dist: metadata.Distribution) -> list[list[str]]:
    import importlib.util

    names = (dist.read_text("top_level.txt") or "").split()
    if not names:
        names = [n for n, dists in metadata.packages_distributions().items() if dist.metadata["Name"] in dists]
    out = []
    for name in sorted(set(names)):
        spec = importlib.util.find_spec(name)
        if spec is None or not spec.submodule_search_locations:
            continue
        for location in spec.submodule_search_locations:
            base = Path(location)
            for path in sorted(base.rglob("*")):
                if path.is_file() and "__pycache__" not in path.parts and path.suffix != ".pyc":
                    out.append([f"{name}/{path.relative_to(base).as_posix()}", sha256_file(path)[0]])
    return out


@functools.lru_cache(maxsize=None)
def _cocotb_identity() -> tuple[str, str]:
    try:
        dist = metadata.distribution("cocotb")
    except metadata.PackageNotFoundError as e:
        raise IdentityError("cocotb is not installed") from e
    return dist.version, dist_content_hash(dist)


def toolchain(runner_name: str) -> Toolchain:
    """The toolchain identity for a runner class name (e.g. ``"Icarus"``)."""
    cocotb_version, cocotb_dist = _cocotb_identity()
    image = os.environ.get("COCOTB_CACHE_IMAGE") or None
    return Toolchain(
        python=python_identity(),
        platform=platform_identity(),
        cocotb_version=cocotb_version,
        cocotb_dist=cocotb_dist,
        simulator=simulator_identity(runner_name),
        shim=__version__,
        image=image,
    )
